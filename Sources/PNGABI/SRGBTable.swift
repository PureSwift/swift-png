/// Takes light, scaled to 255 * 65535, down to the eight bit sample a display is driven with.
///
/// The reference's own expression, kept in its shape rather than rearranged: the span's starting
/// value plus the distance into it, both at the scales the tables are built for.
func sRGBFromLinear(_ linear: UInt32) -> UInt8 {
    let span = Int(linear >> 15)
    let within = (linear & 0x7FFF) * UInt32(sRGBDelta[span])

    return UInt8(truncatingIfNeeded: (UInt32(sRGBBase[span]) &+ (within >> 12)) >> 8)
}
